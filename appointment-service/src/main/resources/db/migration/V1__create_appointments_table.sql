
CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,

    appointment_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    reason VARCHAR(500),

    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT chk_appointments_status
        CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED')),

    CONSTRAINT chk_appointments_future_reason
        CHECK (LENGTH(reason) <= 500)
);

CREATE INDEX idx_appointments_patient_id
    ON appointments(patient_id);

CREATE INDEX idx_appointments_doctor_time
    ON appointments(doctor_id, appointment_time);
